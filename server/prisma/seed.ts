async function main() {
  for (const plantType of plantTypes) {
    const existing = await prisma.plantType.findFirst({
      where: { name: plantType.name, ownerId: null },
    });
    if (existing) {
      await prisma.plantType.update({ where: { id: existing.id }, data: plantType });
    } else {
      await prisma.plantType.create({ data: plantType });
    }
  }
  console.log(`Seeded ${plantTypes.length} plant types successfully!`);
}

main()
  .catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
